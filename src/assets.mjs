import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { extname, join } from 'node:path';
import { DATA_ROOT } from './store.mjs';
import { videoAssets, videoSheetBuffer } from './video.mjs';

const ASSET_DIR = join(DATA_ROOT, 'assets');
const INDEX_FILE = join(DATA_ROOT, 'assets.index.json');
const MD_FILE = join(DATA_ROOT, 'assets.md');
const IMAGE_EXT = new Set(['.png', '.jpg', '.jpeg', '.webp', '.avif', '.gif']);
const MIME = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.avif': 'image/avif', '.gif': 'image/gif' };
const VIDEO_NAMES = () => new Set(videoAssets().map((v) => v.name));

const readIndex = () => {
  if (!existsSync(INDEX_FILE)) return { version: 1, assets: [] };
  try { return JSON.parse(readFileSync(INDEX_FILE, 'utf8')); } catch { return { version: 1, assets: [] }; }
};

const hashOf = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 20);

const writeMd = (index) => {
  const rows = index.assets.map((a) => {
    const seg = Array.isArray(a.segments) && a.segments.length
      ? a.segments.map((s) => `${s.start}-${s.end}s ${s.desc}`).join(' / ')
      : '';
    return `| ${a.name} | ${a.kind ?? 'image'} | ${a.duration ? `${a.duration}s. ` : ''}${a.desc ?? ''} | ${(a.tags ?? []).join(', ')} | ${seg} |`;
  });
  const missing = index.assets.filter((a) => a.missing).map((a) => `- ${a.name}`);
  const md = [
    '# Asset index',
    '',
    'Generated by Custom Hyper. The JSON file is canonical. Do not edit by hand.',
    '',
    '| File | Kind | Description | Tags | Segments |',
    '|---|---|---|---|---|',
    ...rows,
    '',
    missing.length ? '## Missing files' : '',
    ...missing,
    '',
  ].join('\n');
  writeFileSync(MD_FILE, md);
};

const fileEntries = () => readdirSync(ASSET_DIR, { withFileTypes: true })
  .filter((d) => d.isFile() && !d.name.startsWith('.') && IMAGE_EXT.has(extname(d.name).toLowerCase()))
  .map((d) => d.name)
  .sort()
  .map((name) => {
    const file = join(ASSET_DIR, name);
    const buf = readFileSync(file);
    return { name, file, buf, hash: hashOf(buf), ext: extname(name).toLowerCase(), bytes: statSync(file).size };
  });

export const assetStatus = () => {
  const index = readIndex();
  const files = fileEntries();
  const byName = new Map(index.assets.map((a) => [a.name, a]));
  const items = files.map((f) => {
    const old = byName.get(f.name);
    return {
      ...(old ?? {}),
      name: f.name,
      hash: f.hash,
      bytes: f.bytes,
      indexed: Boolean(old && old.hash === f.hash),
      stale: Boolean(old && old.hash !== f.hash),
      missing: false,
    };
  });
  for (const v of videoAssets()) {
    const old = byName.get(v.name);
    items.push({
      ...(old ?? {}),
      name: v.name,
      kind: 'video',
      hash: v.hash,
      bytes: v.bytes,
      duration: v.duration,
      width: v.width,
      height: v.height,
      sampleFps: v.sampleFps,
      count: v.count,
      sheetUrl: v.sheetUrl,
      segments: old?.segments ?? [],
      indexed: Boolean(old && old.hash === v.hash && Array.isArray(old.segments) && old.segments.length),
      stale: Boolean(old && old.hash !== v.hash),
      missing: false,
    });
  }
  for (const old of index.assets) {
    if (!files.some((f) => f.name === old.name) && !videoAssets().some((v) => v.name === old.name)) {
      items.push({ ...old, missing: true, indexed: false });
    }
  }
  writeMd({ assets: items });
  return {
    items,
    index: index.assets,
    missing: items.filter((a) => a.missing).map((a) => a.name),
    unindexed: items.filter((a) => !a.indexed && !a.missing).map((a) => a.name),
    indexed: items.filter((a) => a.indexed).length,
  };
};

const listForPrompt = (files) => files.map((f) => (f.video
  ? `video:${f.name} (duration ${f.video.duration}s, ${f.video.count} frames at ${f.video.sampleFps}/s)`
  : `image:${f.name}`)).join('\n');

const promptFor = (files) => `You are indexing assets for a short-form video engine.
Return one JSON object only:
{"items":[{"name":"exact file name","kind":"photo|product|person|place|graphic|texture|video","desc":"what is visible, 8 to 20 words","tags":["3 to 6 short lowercase tags"],"palette":["#rrggbb"],"segments":[{"start":0,"end":2.5,"desc":"what happens, 5 to 12 words","tags":["2 to 4 tags"]}]}]}
For an image: fill name, kind, desc, tags, palette. Omit segments.
For a video: the image is a contact sheet in time order (left to right, top to bottom), with equal spacing across the clip. Set kind to "video". Cover the whole clip with 2 to 5 segments in order. start and end are seconds, from 0 to the given duration. Say what is shown and what moves, not camera jargon. Use the exact file name.
No markdown.
ASSETS:
${listForPrompt(files)}`;

const parseJson = (text) => {
  const body = String(text ?? '').trim().replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '').trim();
  try { return JSON.parse(body); } catch {
    const a = body.indexOf('{');
    const b = body.lastIndexOf('}');
    if (a >= 0 && b > a) return JSON.parse(body.slice(a, b + 1));
    throw new Error('vision response is not JSON');
  }
};

const callGeminiVision = async ({ apiKey, model, files }) => {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent?key=${encodeURIComponent(apiKey)}`;
  const parts = [{ text: promptFor(files) }];
  for (const f of files) parts.push({ inlineData: { mimeType: MIME[f.ext] ?? 'image/png', data: f.buf.toString('base64') } });
  const res = await fetch(url, {
    method: 'POST', headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      contents: [{ role: 'user', parts }],
      generationConfig: { temperature: 0.15, maxOutputTokens: 2600, responseMimeType: 'application/json' },
    }),
    signal: AbortSignal.timeout(90000),
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`Gemini vision ${res.status}: ${String(text).slice(0, 240)}`);
  const data = JSON.parse(text);
  const out = (data.candidates?.[0]?.content?.parts ?? []).map((p) => p.text ?? '').join('');
  if (!out) throw new Error('Gemini vision returned no text');
  return { items: parseJson(out).items ?? [], usage: { input: data.usageMetadata?.promptTokenCount ?? 0, output: data.usageMetadata?.candidatesTokenCount ?? 0 } };
};

const callOpenAIVision = async ({ apiKey, model, baseUrl, files }) => {
  const root = String(baseUrl || 'https://api.openai.com/v1').replace(/\/$/, '');
  const content = [{ type: 'text', text: promptFor(files) }];
  for (const f of files) content.push({ type: 'image_url', image_url: { url: `data:${MIME[f.ext] ?? 'image/png'};base64,${f.buf.toString('base64')}` } });
  const res = await fetch(`${root}/chat/completions`, {
    method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${apiKey}` },
    body: JSON.stringify({
      model, temperature: 0.15, max_tokens: 2600, response_format: { type: 'json_object' },
      messages: [{ role: 'user', content }],
    }),
    signal: AbortSignal.timeout(90000),
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`LLM vision ${res.status}: ${String(text).slice(0, 240)}`);
  const data = JSON.parse(text);
  const out = data.choices?.[0]?.message?.content ?? '';
  return { items: parseJson(out).items ?? [], usage: { input: data.usage?.prompt_tokens ?? 0, output: data.usage?.completion_tokens ?? 0 } };
};

const cleanSegments = (raw, duration) => (Array.isArray(raw) ? raw : []).slice(0, 6).map((s, i) => {
  const start = Math.max(0, Math.min(duration, Number(s.start ?? i)));
  const end = Math.max(start + 0.05, Math.min(duration, Number(s.end ?? start + 1)));
  return {
    start: Math.round(start * 100) / 100,
    end: Math.round(end * 100) / 100,
    desc: String(s.desc ?? '').replace(/\s+/g, ' ').trim().slice(0, 180),
    tags: (Array.isArray(s.tags) ? s.tags : []).slice(0, 5).map((t) => String(t).toLowerCase().slice(0, 30)).filter(Boolean),
  };
}).filter((s) => s.desc);

export const indexAssets = async ({ provider = 'gemini', model, apiKey, baseUrl, limit = 8 } = {}) => {
  const p = String(provider).toLowerCase();
  if (!apiKey) throw new Error('Indexing needs an API key. Add it once in the key field.');
  const status = assetStatus();
  const pending = status.items.filter((a) => !a.indexed && !a.missing);
  if (!pending.length) return { ok: true, ...status, processed: 0, usage: { input: 0, output: 0 } };
  const files = fileEntries();
  const byName = new Map(files.map((f) => [f.name, f]));
  const videos = videoAssets();
  const videoMap = new Map(videos.map((v) => [v.name, v]));
  const selected = pending.slice(0, Math.max(1, Math.min(12, limit)));
  const payload = selected.map((a) => {
    if (a.kind === 'video') {
      const sheet = videoSheetBuffer(a.name);
      return sheet ? { name: a.name, video: sheet.meta, buf: sheet.buf, ext: '.png' } : null;
    }
    const f = byName.get(a.name);
    return f ? { ...f, video: null } : null;
  }).filter(Boolean);
  if (!payload.length) return { ok: true, ...status, processed: 0, usage: { input: 0, output: 0 } };
  const chosenModel = model || (p === 'gemini' ? 'gemini-2.0-flash' : 'gpt-4o-mini');
  const call = p === 'gemini'
    ? callGeminiVision({ apiKey, model: chosenModel, files: payload })
    : callOpenAIVision({ apiKey, model: chosenModel, baseUrl, files: payload });
  const result = await call;
  const old = readIndex();
  const map = new Map(old.assets.map((a) => [a.name, a]));
  const now = new Date().toISOString();
  selected.forEach((entry, i) => {
    const f = byName.get(entry.name);
    const v = videoMap.get(entry.name);
    const got = result.items.find((x) => String(x.name).trim() === entry.name) ?? result.items[i] ?? {};
    const base = {
      name: entry.name, hash: v ? v.hash : f.hash,
      kind: String(got.kind ?? (v ? 'video' : 'image')).toLowerCase().slice(0, 20),
      desc: String(got.desc ?? '').replace(/\s+/g, ' ').trim().slice(0, 240),
      tags: (Array.isArray(got.tags) ? got.tags : []).slice(0, 8).map((t) => String(t).toLowerCase().slice(0, 30)).filter(Boolean),
      palette: Array.isArray(got.palette) ? got.palette.slice(0, 6).map(String) : [],
      indexedAt: now,
    };
    if (v) {
      base.kind = 'video';
      base.duration = v.duration;
      base.segments = cleanSegments(got.segments, v.duration);
      base.sheetUrl = v.sheetUrl;
      base.frames = v.count;
      base.sampleFps = v.sampleFps;
    }
    map.set(entry.name, base);
  });
  const next = { version: 1, assets: [...map.values()] };
  writeFileSync(INDEX_FILE, JSON.stringify(next, null, 2));
  const after = assetStatus();
  return { ok: true, ...after, processed: selected.length, usage: result.usage, model: chosenModel, provider: p };
};

export const assetDescriptions = () => {
  const status = assetStatus();
  return status.items.filter((a) => !a.missing).map((a) => ({
    name: a.name,
    desc: a.desc ?? '',
    tags: a.tags ?? [],
    kind: a.kind ?? '',
    indexed: a.indexed,
    duration: a.duration ?? 0,
    segments: a.segments ?? [],
  }));
};
